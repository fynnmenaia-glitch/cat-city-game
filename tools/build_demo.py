"""Builds the demo website's files into demo/ (not committed).

The demo is a second Render web service from this same repo, started with
CATCITY_DEMO=1 and the build command
    pip install -r requirements.txt && python tools/build_demo.py
so it always matches main, minus:
  - only four biomes (Cherry, Marsh, Moonstone, Poison) around the village,
  - no staged updates (the 🚀 Release update list stays on the main game only),
  - no comments in the code, and no mention of how or by whom it was made,
  - no links or hints to the main game's address,
  - a small Cat Tok: the phone, the feed, the game clock and the Shop with parcels
    (no making videos and no lives), loaded straight away from demo/cattok-lite/.
"""
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
from jsstrip import strip_css, strip_html, strip_js  # noqa: E402

SRC, OUT = ROOT / 'client', ROOT / 'demo'
BIOME_TOKENS = ('<.17', '>.82', '<.32', '>.66', 'cx<0&&cy>=-1&&cy<=1')
# Biome rule used everywhere in the client: v<.17 cherry, v>.82 poison, v<.32 marsh,
# v>.66 moonstone, otherwise (and the west strip) wild. The demo has no wild land.
BIOME_SWAP = (('<.17', '<.25'), ('>.82', '>.75'), ('<.32', '<.5'), ('>.66', '>=.5'), ('cx<0&&cy>=-1&&cy<=1', 'false'))
WORDS = (
    (r'\bClaude\b', 'the dev team'),
    (r'\bChatGPT\b', 'the dev team'),
    (r'cc-ai-', 'cc-pal-'),
)
FORBIDDEN = re.compile(r'\b(AI|Claude|ChatGPT|OpenAI|Anthropic|GPT|LLM)\b|generated by|onrender\.com', re.I)
DEMO_HEAD = '<script>window.CAT_CITY_DEMO=true;window.CAT_TOK_LITE=true</script>'
CATTOK_LITE = ('cattok-1-phone.js', 'cattok-2-app.js', 'cattok-5-clock.js', 'cattok-6-shop.js')


def tidy_words(text):
    for pattern, new in WORDS:
        text = re.sub(pattern, new, text)
    return text.replace('. the dev team', '. The dev team').replace('>the dev team', '>The dev team').replace("'the dev team", "'The dev team")


def build():
    if OUT.exists():
        shutil.rmtree(OUT)
    shutil.copytree(SRC, OUT, ignore=shutil.ignore_patterns('_trailer*', '*.map', 'staged'))
    (OUT / 'staged').mkdir()
    (OUT / 'staged' / 'manifest.json').write_text('{"updates": []}\n', 'utf-8')
    (OUT / 'cattok-lite').mkdir()
    for name in CATTOK_LITE:
        shutil.copy(SRC / 'staged' / name, OUT / 'cattok-lite' / name)
    problems = []
    for path in sorted(OUT.rglob('*')):
        if path.suffix not in ('.js', '.html', '.css') or not path.is_file():
            continue
        text = path.read_text('utf-8')
        if path.suffix == '.js':
            text = strip_js(text)
            if all(t in text for t in BIOME_TOKENS):
                for old, new in BIOME_SWAP:
                    text = text.replace(old, new)
        elif path.suffix == '.css':
            text = strip_css(text)
        else:
            text = strip_html(text)
            text = text.replace('<head>', '<head>' + DEMO_HEAD, 1)
            text = re.sub(r'<title>[^<]*</title>', '<title>Cat City · Demo</title>', text, count=1)
            text = text.replace('<h1>CAT CITY</h1>', '<h1>CAT CITY <span style="display:inline-block;vertical-align:middle;font-size:.42em;padding:3px 8px;border-radius:999px;background:#ffd45c;color:#3a2440;letter-spacing:.08em">DEMO</span></h1>', 1)
            text = text.replace("<b>🐾 CAT CITY</b>", "<b>🐾 CAT CITY · DEMO</b>", 1)
            text = text.replace('</body>', ''.join('<script src="/cattok-lite/%s" defer></script>' % n for n in CATTOK_LITE) + '</body>', 1)
        text = tidy_words(text)
        for m in FORBIDDEN.finditer(text):
            line = text[:m.start()].count('\n') + 1
            problems.append('%s:%d: %s' % (path.relative_to(OUT), line, text[max(0, m.start() - 40):m.end() + 40].replace('\n', ' ')))
        path.write_text(text, 'utf-8')
    if problems:
        print('Demo build stopped: these still give it away:\n' + '\n'.join(problems[:40]))
        sys.exit(1)
    print('Demo built in', OUT)


if __name__ == '__main__':
    build()
