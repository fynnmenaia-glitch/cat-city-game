# accented letters (Portuguese/French names)
for base, acc in [('a','á'),('a','à'),('a','â'),('a','ã'),('e','é'),('e','ê'),('i','í'),('o','ó'),('o','ô'),('o','õ'),('u','ú'),('c','ç')]:
    rows, w = G[base]
    rows = list(rows)
    if acc == 'ç':
        rows = rows + ['..#..'[:w], '.#...'[:w]] if len(rows) == 7 else rows
    else:
        mark = {'á':'...#.','à':'.#...','â':'.#.#.','ã':'.#.##','é':'...#.','ê':'.#.#.','í':'.#.','ó':'...#.','ô':'.#.#.','õ':'.#.##','ú':'...#.'}[acc]
        two = {'â':('..#..','.#.#.'),'ê':('..#..','.#.#.'),'ô':('..#..','.#.#.'),'ã':('.#.#.','#.#..'),'õ':('.#.#.','#.#..')}
        if acc in two:
            rows[0] = two[acc][0][:w].ljust(w, '.'); rows[1] = two[acc][1][:w].ljust(w, '.')
        else:
            rows[0] = mark[:w].ljust(w, '.')
            rows[1] = '.' * w
    G[acc] = (rows, w)

def build(out):
    fb = FontBuilder(PX * 10, isTTF=True)
    names = ['.notdef'] + [f'u{ord(c):04X}' for c in G]
    fb.setupGlyphOrder(names)
    cmap = {ord(c): f'u{ord(c):04X}' for c in G}
    fb.setupCharacterMap(cmap)
    glyphs, metrics = {}, {}
    def draw(rows):
        pen = TTGlyphPen(None)
        for r, row in enumerate(rows):
            for c, ch in enumerate(row):
                if ch != '#':
                    continue
                x0 = c * PX
                top = (6 - r) * PX + PX  # row 6 is the baseline row
                y0, y1 = top - PX, top
                pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x0 + PX, y1)); pen.lineTo((x0 + PX, y0)); pen.closePath()
        return pen.glyph()
    pen = TTGlyphPen(None)
    pen.moveTo((0, 0)); pen.lineTo((0, 700)); pen.lineTo((400, 700)); pen.lineTo((400, 0)); pen.closePath()
    glyphs['.notdef'] = pen.glyph(); metrics['.notdef'] = (500, 0)
    for ch, (rows, w) in G.items():
        n = f'u{ord(ch):04X}'
        glyphs[n] = draw(rows)
        metrics[n] = ((w + 1) * PX, 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASC * PX, descent=-DESC * PX)
    fb.setupNameTable({'familyName': 'Cat City Pixel', 'styleName': 'Regular', 'uniqueFontIdentifier': 'CatCityPixel-Regular', 'fullName': 'Cat City Pixel', 'psName': 'CatCityPixel-Regular', 'version': 'Version 1.000', 'copyright': 'Original font made for Cat City, 2026'})
    fb.setupOS2(sTypoAscender=ASC * PX, sTypoDescender=-DESC * PX, sTypoLineGap=PX, usWinAscent=ASC * PX + PX, usWinDescent=DESC * PX + PX, sxHeight=500, sCapHeight=700, achVendID='CATC', fsType=0)
    fb.setupPost()
    fb.setupHead(unitsPerEm=PX * 10)
    fb.save(out + '.ttf')
    from fontTools.ttLib import TTFont
    f = TTFont(out + '.ttf')
    try:
        f.flavor = 'woff2'; f.save(out + '.woff2')
    except Exception as e:
        print('woff2 failed, using woff', e)
        f.flavor = 'woff'; f.save(out + '.woff')
    print('glyphs', len(G))

build(sys.argv[1] if len(sys.argv) > 1 else 'CatCityPixel')
